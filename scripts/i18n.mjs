#!/usr/bin/env node
// scripts/i18n.mjs — one CLI for everything translation-related.
//
//   npm run i18n:sync                  regenerate src/i18n/locales/<lang>/index.ts from the JSON files
//   npm run i18n:check                 verify every language against English (missing keys, stray keys, placeholders)
//   npm run i18n:add -- <code> "<Native name>" "<English name>" [--dir=rtl] [--intl=mr-IN] [--og=mr_IN]
//   npm run i18n:audit                 list user-visible strings still hardcoded in JSX (not yet translatable)
//
// See docs/I18N.md.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LOCALES = path.join(ROOT, "src/i18n/locales");
const REGISTRY = path.join(ROOT, "src/i18n/languages.ts");
const SOURCE = "en";
const PLURAL = /_(zero|one|two|few|many|other)$/;

const readJson = (f) => JSON.parse(fs.readFileSync(f, "utf8"));
const writeJson = (f, o) => fs.writeFileSync(f, JSON.stringify(o, null, 2) + "\n");
const languages = () =>
  fs.readdirSync(LOCALES, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort((a, b) =>
    a === SOURCE ? -1 : b === SOURCE ? 1 : a.localeCompare(b));
const namespaces = (lang) =>
  fs.existsSync(path.join(LOCALES, lang))
    ? fs.readdirSync(path.join(LOCALES, lang)).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).sort()
    : [];
const placeholders = (s) => [...String(s).matchAll(/\{\{\s*([\w.]+)\s*\}\}/g)].map((m) => m[1]).sort().join(",");
const tags = (s) => [...String(s).matchAll(/<\/?([a-zA-Z][\w-]*)\s*\/?>/g)].map((m) => m[0].replace(/\s+/g, "")).sort().join(",");

// ───────────────────────── sync ─────────────────────────
function syncIndexes() {
  const enNs = namespaces(SOURCE);
  for (const lang of languages()) {
    const nss = lang === SOURCE ? enNs : namespaces(lang);
    const imp = nss.map((n) => `import ${n} from "./${n}.json";`).join("\n");
    const spread = nss.map((n) => `  ...namespaced("${n}", ${n}),`).join("\n");
    const typed = lang === SOURCE
      ? `const ${lang} = {\n${spread}\n};\n\nexport default ${lang};\n`
      : `const dictionary: PartialDictionary = {\n${spread}\n};\n\nexport default dictionary;\n`;
    const header = lang === SOURCE
      ? `// GENERATED by \`npm run i18n:sync\` from the *.json files in this folder — do not edit by hand.\n// English is the SOURCE language: bundled eagerly, it defines the type-checked TranslationKey union\n// and is the fallback for every other language.\n`
      : `// GENERATED by \`npm run i18n:sync\` from the *.json files in this folder — do not edit by hand.\n// Lazy-loaded as its own chunk. Keys missing here fall back to English (see \`npm run i18n:check\`).\n`;
    const types = lang === SOURCE ? "" : `import type { PartialDictionary } from "@/types/i18n.types";\n`;
    fs.writeFileSync(path.join(LOCALES, lang, "index.ts"),
      `${header}import { namespaced } from "../../namespaced";\n${types}${imp}\n\n${typed}`);
  }
  console.log(`synced indexes for: ${languages().join(", ")}`);
}

// ───────────────────────── check ─────────────────────────
function check({ quiet = false } = {}) {
  const problems = [];
  const stats = [];
  const en = {};
  for (const ns of namespaces(SOURCE)) en[ns] = readJson(path.join(LOCALES, SOURCE, `${ns}.json`));
  for (const lang of languages().filter((l) => l !== SOURCE)) {
    let total = 0, done = 0;
    for (const ns of Object.keys(en)) {
      const file = path.join(LOCALES, lang, `${ns}.json`);
      const dict = fs.existsSync(file) ? readJson(file) : {};
      for (const [k, v] of Object.entries(en[ns])) {
        total++;
        const tv = dict[k];
        if (tv === undefined || tv === "") { problems.push({ level: "missing", msg: `${lang}/${ns}: missing "${k}"` }); continue; }
        done++;
        if (placeholders(v) !== placeholders(tv))
          problems.push({ level: "error", msg: `${lang}/${ns}.${k}: placeholders differ  en={${placeholders(v)}}  ${lang}={${placeholders(tv)}}` });
        if (tags(v) !== tags(tv))
          problems.push({ level: "error", msg: `${lang}/${ns}.${k}: rich-text tags differ  en=[${tags(v)}]  ${lang}=[${tags(tv)}]` });
      }
      for (const k of Object.keys(dict))
        if (!(k in en[ns])) problems.push({ level: "error", msg: `${lang}/${ns}: stray key "${k}" (not in English)` });
    }
    for (const ns of namespaces(lang)) if (!(ns in en)) problems.push({ level: "error", msg: `${lang}: namespace "${ns}" has no English source file` });
    stats.push({ lang, total, done });
  }
  // Plural sanity: English plural families must be complete (one + other).
  for (const [ns, d] of Object.entries(en)) {
    for (const k of Object.keys(d)) {
      const m = k.match(PLURAL);
      if (m && m[1] === "one" && !(k.replace(PLURAL, "_other") in d)) problems.push({ level: "error", msg: `en/${ns}: "${k}" has no matching _other form` });
    }
  }
  const errors = problems.filter((p) => p.level === "error");
  const missing = problems.filter((p) => p.level === "missing");
  if (!quiet) {
    for (const s of stats) console.log(`${s.lang}: ${s.done}/${s.total} keys translated (${s.total ? Math.round((100 * s.done) / s.total) : 100}%)`);
    errors.forEach((p) => console.error("ERROR  " + p.msg));
    missing.slice(0, 40).forEach((p) => console.warn("MISSING " + p.msg));
    if (missing.length > 40) console.warn(`… and ${missing.length - 40} more missing keys`);
  }
  return { errors, missing, stats };
}

// ───────────────────────── unused keys (informational) ─────────────────────────
function unusedKeys() {
  const srcDir = path.join(ROOT, "src");
  let blob = "";
  (function walk(d) {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) { if (!p.includes(path.join("src", "i18n", "locales"))) walk(p); }
      else if (/\.(tsx?|jsx?)$/.test(e.name)) blob += fs.readFileSync(p, "utf8") + "\n";
    }
  })(srcDir);
  const out = [];
  for (const ns of namespaces(SOURCE)) for (const k of Object.keys(readJson(path.join(LOCALES, SOURCE, `${ns}.json`)))) {
    const base = k.replace(PLURAL, "");
    const full = `${ns}.${base}`;
    if (!blob.includes(full)) out.push(`${ns}.${k}`);
  }
  return out;
}

// ───────────────────────── add a language ─────────────────────────
function addLanguage() {
  const [code, nativeName, name] = process.argv.slice(3).filter((a) => !a.startsWith("--"));
  const flag = (n, d) => (process.argv.find((a) => a.startsWith(`--${n}=`)) || "").split("=")[1] || d;
  if (!code || !nativeName || !name) { console.error('usage: i18n:add -- <code> "<Native name>" "<English name>" [--dir=rtl] [--intl=xx-YY] [--og=xx_YY]'); process.exit(2); }
  if (!/^[a-z]{2,3}$/.test(code)) { console.error("language code must be 2-3 lowercase letters, e.g. mr, ta, bn"); process.exit(2); }
  if (languages().includes(code)) { console.error(`"${code}" already exists`); process.exit(1); }
  const dir = flag("dir", "ltr"), intl = flag("intl", `${code}-IN`), og = flag("og", `${code}_IN`);
  let reg = fs.readFileSync(REGISTRY, "utf8");
  const marker = "  // ADD NEW LANGUAGES ABOVE THIS LINE";
  if (!reg.includes(marker)) { console.error("registry marker comment not found in src/i18n/languages.ts"); process.exit(1); }
  reg = reg.replace(marker, `  { code: ${JSON.stringify(code)}, name: ${JSON.stringify(name)}, nativeName: ${JSON.stringify(nativeName)}, dir: ${JSON.stringify(dir)}, intlLocale: ${JSON.stringify(intl)}, ogLocale: ${JSON.stringify(og)} },\n${marker}`);
  fs.writeFileSync(REGISTRY, reg);
  // Scaffold: every namespace file with the SAME keys, empty values -> falls back to English until translated.
  fs.mkdirSync(path.join(LOCALES, code), { recursive: true });
  for (const ns of namespaces(SOURCE)) {
    const en = readJson(path.join(LOCALES, SOURCE, `${ns}.json`));
    writeJson(path.join(LOCALES, code, `${ns}.json`), Object.fromEntries(Object.keys(en).map((k) => [k, ""])));
  }
  syncIndexes();
  console.log(`\nAdded "${code}" (${name}). Next:\n  1. Fill in src/i18n/locales/${code}/*.json (empty = English fallback)\n  2. npm run i18n:check   (shows % done, validates placeholders)\n  3. Add Noto font / line-height rules in src/index.css if the script needs them (see docs/I18N.md)\nThe language switcher, <html lang>, storage and og:locale pick it up automatically.`);
}

// ───────────────────────── audit hardcoded strings ─────────────────────────
async function audit() {
  const ts = (await import("typescript")).default;
  const ATTRS = new Set(["placeholder", "title", "label", "aria-label", "alt", "description", "helperText", "emptyText", "tooltip", "text", "heading", "subtitle", "hint", "caption"]);
  const hasLetters = (s) => /[A-Za-z]{2,}/.test(s);
  const skip = (s) => !hasLetters(s) || /^[A-Z0-9]{2,6}$/.test(s.trim()) || (/^[a-z0-9_\-:.\/#@]+$/.test(s.trim()) && /[_\-:.\/#@0-9]/.test(s.trim())) || /^Policy Niketan$/i.test(s.trim());
  const found = {};
  (function walk(d) {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) { if (!["test", "i18n", "types"].includes(e.name)) walk(p); continue; }
      if (!p.endsWith(".tsx")) continue;
      const sf = ts.createSourceFile(p, fs.readFileSync(p, "utf8"), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
      const hits = [];
      (function v(n) {
        const line = () => sf.getLineAndCharacterOfPosition(n.getStart()).line + 1;
        if (ts.isJsxText(n)) { const t = n.text.replace(/\s+/g, " ").trim(); if (t && !skip(t)) hits.push([line(), t]); }
        if (ts.isJsxAttribute(n) && ATTRS.has(n.name.getText()) && n.initializer && ts.isStringLiteral(n.initializer) && !skip(n.initializer.text)) hits.push([line(), n.initializer.text]);
        ts.forEachChild(n, v);
      })(sf);
      if (hits.length) found[path.relative(ROOT, p)] = hits;
    }
  })(path.join(ROOT, "src"));
  const files = Object.entries(found).sort((a, b) => b[1].length - a[1].length);
  const total = files.reduce((n, [, h]) => n + h.length, 0);
  const verbose = process.argv.includes("--verbose");
  for (const [f, hits] of files) { console.log(`${String(hits.length).padStart(4)}  ${f}`); if (verbose) hits.slice(0, 200).forEach(([l, t]) => console.log(`        ${l}: ${t.slice(0, 90)}`)); }
  console.log(`\n${total} hardcoded user-visible strings in ${files.length} files.` + (total ? "  (run with --verbose for line numbers)" : "  All JSX text is translatable."));
  return total;
}

const cmd = process.argv[2];
if (cmd === "sync") syncIndexes();
else if (cmd === "check") {
  const r = check();
  if (process.argv.includes("--unused")) { const u = unusedKeys(); console.log(u.length ? `\nUNUSED keys (${u.length}):\n  ${u.join("\n  ")}` : "\nNo unused keys."); }
  process.exit(r.errors.length || (process.argv.includes("--strict") && r.missing.length) ? 1 : 0);
}
else if (cmd === "add") addLanguage();
else if (cmd === "audit") { const n = await audit(); process.exit(process.argv.includes("--strict") && n ? 1 : 0); }
else if (cmd) { console.error("usage: i18n.mjs <sync|check [--strict] [--unused]|add|audit [--verbose] [--strict]>"); process.exit(2); }
export { syncIndexes, check, languages, namespaces, readJson, writeJson, LOCALES, ROOT, REGISTRY, SOURCE };
